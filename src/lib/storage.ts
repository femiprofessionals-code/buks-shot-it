import "server-only";
import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

/**
 * Cloudflare R2 (S3-compatible) storage.
 * - public bucket: web-sized portfolio images, served from R2_PUBLIC_BASE_URL
 * - private bucket: originals and client gallery files, reached only through short-lived signed links
 */
export type Bucket = "public" | "private";

type StorageConfig = {
  endpoint: string;
  accessKeyId: string;
  secretAccessKey: string;
  buckets: Record<Bucket, string>;
  publicBaseUrl: string;
};

export function storageConfig(): StorageConfig | null {
  const accountId = process.env.R2_ACCOUNT_ID;
  const endpoint = process.env.R2_ENDPOINT ?? (accountId ? `https://${accountId}.r2.cloudflarestorage.com` : "");
  const accessKeyId = process.env.R2_ACCESS_KEY_ID ?? "";
  const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY ?? "";
  const pub = process.env.R2_PUBLIC_BUCKET ?? "";
  const priv = process.env.R2_PRIVATE_BUCKET ?? "";
  const publicBaseUrl = process.env.R2_PUBLIC_BASE_URL ?? "";
  if (!endpoint || !accessKeyId || !secretAccessKey || !pub || !priv || !publicBaseUrl) return null;
  return { endpoint, accessKeyId, secretAccessKey, buckets: { public: pub, private: priv }, publicBaseUrl };
}

let cached: { client: S3Client; cfg: StorageConfig } | null = null;

function client() {
  if (cached) return cached;
  const cfg = storageConfig();
  if (!cfg) throw new Error("STORAGE_NOT_CONFIGURED");
  const c = new S3Client({
    region: "auto",
    endpoint: cfg.endpoint,
    forcePathStyle: true,
    credentials: { accessKeyId: cfg.accessKeyId, secretAccessKey: cfg.secretAccessKey },
  });
  cached = { client: c, cfg };
  return cached;
}

export const ALLOWED_UPLOAD_TYPES = ["image/jpeg", "image/png", "image/webp", "image/heic", "image/heif", "image/tiff"] as const;
export const MAX_UPLOAD_BYTES = 80 * 1024 * 1024; // 80 MB: large camera JPEGs and TIFFs

/** A one-time upload link the browser uses to send a file straight to storage. Valid for 15 minutes. */
export async function presignUpload(bucket: Bucket, key: string, contentType: string): Promise<string> {
  const { client: c, cfg } = client();
  return getSignedUrl(c, new PutObjectCommand({ Bucket: cfg.buckets[bucket], Key: key, ContentType: contentType }), {
    expiresIn: 15 * 60,
  });
}

/** A short-lived download link (default 10 minutes). */
export async function presignDownload(bucket: Bucket, key: string, filename?: string, seconds = 600): Promise<string> {
  const { client: c, cfg } = client();
  return getSignedUrl(
    c,
    new GetObjectCommand({
      Bucket: cfg.buckets[bucket],
      Key: key,
      ResponseContentDisposition: filename ? `attachment; filename="${filename.replace(/["\\\r\n]/g, "")}"` : undefined,
    }),
    { expiresIn: seconds },
  );
}

export async function getObjectBytes(bucket: Bucket, key: string): Promise<Buffer> {
  const { client: c, cfg } = client();
  const res = await c.send(new GetObjectCommand({ Bucket: cfg.buckets[bucket], Key: key }));
  if (!res.Body) throw new Error("EMPTY_OBJECT");
  return Buffer.from(await res.Body.transformToByteArray());
}

export async function putObject(bucket: Bucket, key: string, body: Buffer, contentType: string, cacheControl?: string) {
  const { client: c, cfg } = client();
  await c.send(
    new PutObjectCommand({ Bucket: cfg.buckets[bucket], Key: key, Body: body, ContentType: contentType, CacheControl: cacheControl }),
  );
}

export async function deleteObject(bucket: Bucket, key: string) {
  const { client: c, cfg } = client();
  await c.send(new DeleteObjectCommand({ Bucket: cfg.buckets[bucket], Key: key }));
}

export function publicUrl(key: string): string {
  const cfg = storageConfig();
  if (!cfg) throw new Error("STORAGE_NOT_CONFIGURED");
  return `${cfg.publicBaseUrl.replace(/\/$/, "")}/${key.split("/").map(encodeURIComponent).join("/")}`;
}

/** Keys are generated by the server, never taken from the browser. */
export function newKey(prefix: string, ext: string): string {
  const safeExt = ext.toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 5) || "bin";
  return `${prefix}/${crypto.randomUUID()}.${safeExt}`;
}
